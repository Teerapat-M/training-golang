// ===============================================================
// บทที่ 1: Array (อาร์เรย์ขนาดตายตัว)
// ---------------------------------------------------------------
// - ขนาดเป็นส่วนหนึ่งของชนิด: [4]string กับ [5]string คือคนละชนิดกัน
// - เพิ่ม/ลบช่องไม่ได้จริงๆ ทำได้แค่ "เปลี่ยนค่าในช่อง"
// - เหมาะกับข้อมูลที่รู้จำนวนแน่นอน เช่น 7 วันในสัปดาห์
// รัน: go run ./01-array
// ===============================================================
package main

import "fmt"

func main() {
	// ---------- สร้าง (ประกาศ) ----------
	// ประกาศแบบไม่ใส่ค่า: Go จะใส่ zero value ให้ ("" สำหรับ string)
	var products [4]string
	fmt.Println("เริ่มต้น:", products) // [   ]

	// ประกาศพร้อมใส่ค่า (array literal)
	scores := [3]int{90, 75, 60}
	fmt.Println("scores:", scores)

	// ---------- ADD (เพิ่ม) ----------
	// array เพิ่มช่องไม่ได้ เลยทำได้แค่ใส่ค่าลงในช่องที่ยังว่าง
	products[0] = "Macbook"
	products[1] = "iPhone"
	products[2] = "iPad"
	fmt.Println("หลังเพิ่ม:", products)

	// ---------- ACCESS (เข้าถึง) ----------
	// ใช้ index เริ่มที่ 0
	fmt.Println("ตัวแรก:", products[0])
	fmt.Println("จำนวนช่อง len():", len(products)) // 4 เสมอ

	// วนลูปด้วย for range -> ได้ทั้ง index (i) และค่า (name)
	for i, name := range products {
		fmt.Printf("  index %d = %q\n", i, name)
	}

	// ---------- UPDATE (แก้ไข) ----------
	// เขียนทับด้วย = (ไม่ใช่ := เพราะไม่ได้สร้างตัวแปรใหม่)
	products[1] = "iPhone 16"
	fmt.Println("หลังแก้ไข:", products)

	// ---------- DELETE (ลบ) ----------
	// ลบช่องจริงไม่ได้ ทำได้แค่ "รีเซ็ต" ให้กลับเป็น zero value
	products[2] = ""
	fmt.Println("หลังลบ (รีเซ็ต):", products, "len ยังเป็น", len(products))

	// ---------- ข้อควรระวัง ----------
	// array ถูก "คัดลอกทั้งก้อน" เวลาเอาไปใส่ตัวแปรอื่นหรือส่งเข้าฟังก์ชัน
	copyArr := products
	copyArr[0] = "เปลี่ยนแค่ในสำเนา"
	fmt.Println("ต้นฉบับ:", products[0], "| สำเนา:", copyArr[0])

	// products[10] = "x" // <- เปิดบรรทัดนี้จะ compile ไม่ผ่าน: index out of range
}
